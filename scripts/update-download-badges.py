#!/usr/bin/env python3
"""Tally downloads, clones, stars and forks across Infinitode's public repos.

Nothing is hand-maintained. Every public repository owned by one of OWNERS is
discovered from the GitHub API and counted; anything else is ignored. Packages
are only counted when they are public and belong to one of those repositories.

What is measured
----------------
Stars and forks (exact, all-time)
    ``stargazers_count`` and ``forks_count`` from the GitHub repo listing.

Downloads
    PyPI (all-time). A PyPI package belongs to a repo when it has the repo's
    name AND either its PyPI metadata links back to the repo, or the repo's own
    packaging file (pyproject.toml / setup.py / setup.cfg) declares that name.
    Same-named packages by other people fail both checks, so they are skipped.
      1. pepy v2 API when PEPY_API_KEY is set (exact counts), otherwise
      2. shields.io ``/pepy/dt`` badge (rounded figures).
    jsDelivr (last 12 months). shields.io ``/jsdelivr/gh/hy`` for every counted
    repo. jsDelivr publishes period stats only; there is no all-time figure.

Clones
    GitHub traffic API ``/traffic/clones``. It only returns the last 14 days and
    needs push access to the repository, so it requires the TRAFFIC_TOKEN secret.
    Daily counts are merged into CLONE_HISTORY, which is the all-time record.
    The total therefore starts from the first run that has a token.

Safety
------
A failed fetch never overwrites published numbers. If the repo listing fails,
nothing is written. If every download source fails, nothing is written. A
download total is only published when it is not more than 5% below the figure
already shown (download totals only increase, so a drop means partial data).
Stars, forks and clones are not guarded, because they can legitimately fall.

Usage::

    python3 scripts/update-download-badges.py --readme profile/README.md
    python3 scripts/update-download-badges.py --dry-run

Environment: PEPY_API_KEY (optional), GITHUB_TOKEN (optional, raises the GitHub
rate limit), TRAFFIC_TOKEN (optional, enables clone counts).
"""

from __future__ import annotations

import argparse
import base64
import copy
import gzip
import json
import os
import re
import sys
import urllib.error
import urllib.request

# --- what gets counted -------------------------------------------------------

# (login, account type). Only public repositories owned by these accounts count.
OWNERS = (("johanbeytell1", "user"), ("Infinitode", "org"))

# hy = hits per year, the longest window jsDelivr exposes.
JSDELIVR_PERIOD = "hy"

# Clone history, kept in the repo so the all-time total survives the 14-day window.
CLONE_HISTORY = "data/clone-history.json"

GITHUB_API = "https://api.github.com"
GITHUB_HEADERS = {"Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"}
MAX_PAGES = 20
PACKAGING_FILES = ("pyproject.toml", "setup.py", "setup.cfg")

PYPI_JSON = "https://pypi.org/pypi/{pkg}/json"
PEPY_V2 = "https://api.pepy.tech/api/v2/projects/{pkg}"
SHIELDS_PYPI = "https://img.shields.io/pepy/dt/{pkg}"
SHIELDS_JSDELIVR = "https://img.shields.io/jsdelivr/gh/{period}/{repo}"

# A new total this far below the published one counts as partial data and is
# refused. 5% absorbs display rounding while still catching a missing source
# (dropping one of eleven sources moves the total by ~9%).
DROP_TOLERANCE = 0.05

# Keys that hold an all-time count, highest confidence first.
COUNT_KEYS = ("total_downloads", "totaldownloads", "totalhits", "downloads", "hits")

START_MARK = "<!-- TOTAL-DOWNLOADS:START (generated by scripts/update-download-badges.py) -->"
END_MARK = "<!-- TOTAL-DOWNLOADS:END -->"
START_RE = re.compile(
    r"<!--\s*TOTAL-DOWNLOADS:START[^\n]*\n.*?<!--\s*TOTAL-DOWNLOADS:END\s*-->", re.S
)
ANCHOR = "![](https://komarev.com/ghpvc/?username=infinitode&color=5d17eb)"
BADGE_COLOR = "5d17eb"
NOT_AVAILABLE = "n%2Fa"  # shields.io path form of "n/a"
BADGE_VALUE_RE = re.compile(r"Total%20Downloads-([0-9][0-9.,]*)([kMB]?)-")
CURRENT_DOWNLOADS_RE = re.compile(r"Total%20Downloads-([^-\s)]+)-")

TEXT_RE = re.compile(r"<text[^>]*>([^<]*)</text>")
SHIELDS_VALUE_RE = re.compile(r"^([0-9][0-9.,]*)\s*([kMB]?)$")
_SUFFIX = {"": 1, "k": 1_000, "M": 1_000_000, "B": 1_000_000_000}

_PY_NAME_RE = re.compile(r"""\bname\s*=\s*["']([A-Za-z0-9][A-Za-z0-9._-]*)["']""")
_CFG_NAME_RE = re.compile(r"^name\s*=\s*([A-Za-z0-9][A-Za-z0-9._-]*)\s*$", re.M)


# --- network (the only I/O in this module) -----------------------------------


def fetch(url, headers=None, timeout=30):
    """Return ``(body_bytes, content_type)`` for *url*."""
    request = urllib.request.Request(
        url,
        headers={
            "User-Agent": "Infinitode-download-badge/1.0",
            "Accept": "application/json, image/svg+xml, */*",
            **(headers or {}),
        },
    )
    with urllib.request.urlopen(request, timeout=timeout) as response:
        body = response.read()
        if response.headers.get("Content-Encoding", "").lower() == "gzip":
            body = gzip.decompress(body)
        return body, (response.headers.get("Content-Type") or "")


def fetch_json(url, headers=None, timeout=30):
    return json.loads(fetch(url, headers, timeout)[0].decode("utf-8"))


def fetch_text(url, headers=None, timeout=30):
    return fetch(url, headers, timeout)[0].decode("utf-8", "replace")


def github_headers(token=None):
    headers = dict(GITHUB_HEADERS)
    if token:
        headers["Authorization"] = f"Bearer {token}"
    return headers


# --- parsers and pure helpers (no I/O) ---------------------------------------


def _search(node, key):
    """Depth-first search for the first numeric value stored under *key*."""
    if isinstance(node, dict):
        for name, value in node.items():
            if name.lower() == key and isinstance(value, (int, float)) and not isinstance(value, bool):
                return value
        for value in node.values():
            found = _search(value, key)
            if found is not None:
                return found
    elif isinstance(node, list):
        for item in node:
            found = _search(item, key)
            if found is not None:
                return found
    return None


def find_count(payload):
    """Return the first all-time count found anywhere in a decoded payload."""
    for key in COUNT_KEYS:
        value = _search(payload, key)
        if value is not None:
            return int(value)
    return None


def parse_shields_badge(svg):
    """Pull the numeric value out of a shields.io SVG.

    shields.io renders the value as the last ``<text>`` element. Error badges
    ("unavailable", "no longer available") hold no number and yield ``None``.
    """
    for text in reversed([t.strip() for t in TEXT_RE.findall(svg or "")]):
        match = SHIELDS_VALUE_RE.match(text)
        if match:
            number = float(match.group(1).replace(",", ""))
            return int(round(number * _SUFFIX[match.group(2)]))
    return None


def format_count(total):
    """Compact, URL-safe badge value: 1234567 -> '1.23M', 45678 -> '45.7k'."""
    if total >= 1_000_000_000:
        return f"{total / 1e9:.2f}B"
    if total >= 999_950:  # 999_999 would render as the ugly "1000.0k"
        return f"{total / 1e6:.2f}M"
    if total >= 1_000:
        return f"{total / 1e3:.1f}k"
    return str(total)


def parse_badge_value(text):
    """Read the download total currently published in the badge, or ``None``."""
    match = BADGE_VALUE_RE.search(text or "")
    if not match:
        return None
    return int(round(float(match.group(1).replace(",", "")) * _SUFFIX[match.group(2)]))


def normalize_name(name):
    """PyPI's name normalisation (PEP 503): case-insensitive, runs of -_. equal."""
    return re.sub(r"[-_.]+", "-", name).lower()


def is_counted(repo, owner):
    """True for a public repository that is owned by *owner*."""
    login = (repo.get("owner") or {}).get("login", "")
    return (
        login.lower() == owner.lower()
        and not repo.get("private")
        and repo.get("visibility", "public") == "public"
    )


def links_back(meta, owner, repo):
    """True if the PyPI project's metadata links to github.com/owner/repo."""
    info = meta.get("info") or {}
    urls = [info.get(key) for key in ("home_page", "download_url", "project_url")]
    urls += list((info.get("project_urls") or {}).values())
    text = " ".join(str(url) for url in urls if url) + "\n" + (info.get("description") or "")
    pattern = rf"github\.com/{re.escape(owner)}/{re.escape(repo)}(?![\w-]|\.\w)"
    return re.search(pattern, text, re.I) is not None


def packaging_names(filename, text):
    """Package names a packaging file declares."""
    if filename == "setup.cfg":
        return set(_CFG_NAME_RE.findall(text))
    return set(_PY_NAME_RE.findall(text))


def merge_clones(history, full_name, daily):
    """Fold one repo's daily clone counts into *history* (in place).

    GitHub reports the last 14 days in full on every call, so a day is simply
    overwritten with the latest count. Days that are zero are not stored.
    """
    days = history.setdefault("repos", {}).setdefault(full_name, {})
    for day, count in daily.items():
        if count > 0:
            days[day] = count
        else:
            days.pop(day, None)
    if not days:
        history["repos"].pop(full_name, None)


def history_total(history):
    return sum(sum(days.values()) for days in history.get("repos", {}).values())


def render_block(values):
    """The badge block. *values* is a list of ``(label, badge_text)`` pairs."""
    lines = [START_MARK]
    for label, text in values:
        label_path = label.replace(" ", "%20")
        lines.append(f"![{label}](https://img.shields.io/badge/{label_path}-{text}-{BADGE_COLOR})")
    lines.append(END_MARK)
    return "\n".join(lines)


def update_readme(text, values):
    """Replace (or insert) the badge block. Returns ``(new_text, changed)``."""
    block = render_block(values)
    if START_RE.search(text):
        new_text, _ = START_RE.subn(lambda _match: block, text, count=1)
        return new_text, new_text != text
    if ANCHOR in text:  # first run: drop the badges under the visitor counter
        return text.replace(ANCHOR, f"{ANCHOR}\n{block}", 1), True
    return text, False


def current_downloads_text(text):
    """The badge text currently shown for downloads, or ``None``."""
    match = CURRENT_DOWNLOADS_RE.search(text or "")
    return match.group(1) if match else None


# --- discovery ---------------------------------------------------------------


def list_public_repos(owner, kind, fetch_json=None, token=None):
    """Every public repository owned by *owner*. Raises on API failure."""
    fetch_json = fetch_json or globals()["fetch_json"]
    base = f"{GITHUB_API}/{'orgs' if kind == 'org' else 'users'}/{owner}/repos"
    listing = "public" if kind == "org" else "owner"
    repos = []
    for page in range(1, MAX_PAGES + 1):
        batch = fetch_json(f"{base}?type={listing}&per_page=100&page={page}", github_headers(token))
        if not isinstance(batch, list):
            raise ValueError(f"unexpected repository listing for {owner}")
        repos.extend(repo for repo in batch if is_counted(repo, owner))
        if len(batch) < 100:
            break
    return repos


def discover_repos(fetch_json=None, token=None):
    repos = []
    for owner, kind in OWNERS:
        repos.extend(list_public_repos(owner, kind, fetch_json=fetch_json, token=token))
    return repos


def declared_names(owner, repo, fetch_json=None, token=None):
    """Package names declared by the repo's own packaging files."""
    fetch_json = fetch_json or globals()["fetch_json"]
    try:
        listing = fetch_json(f"{GITHUB_API}/repos/{owner}/{repo}/contents", github_headers(token))
    except urllib.error.HTTPError as error:
        if error.code == 404:
            return set()
        raise
    names = set()
    for item in listing if isinstance(listing, list) else []:
        if item.get("type") == "file" and item.get("name") in PACKAGING_FILES:
            blob = fetch_json(item["url"], github_headers(token))
            text = base64.b64decode(blob.get("content", "")).decode("utf-8", "replace")
            names |= packaging_names(item["name"], text)
    return names


def pypi_package_for(repo, fetch_json=None, token=None):
    """The PyPI package that belongs to *repo*, or ``None``."""
    fetch_json = fetch_json or globals()["fetch_json"]
    owner, name = repo["owner"]["login"], repo["name"]
    package = normalize_name(name)
    try:
        meta = fetch_json(PYPI_JSON.format(pkg=package))
    except urllib.error.HTTPError as error:
        if error.code == 404:
            return None
        raise
    if links_back(meta, owner, name):
        return package
    declared = {normalize_name(n) for n in declared_names(owner, name, fetch_json, token)}
    return package if package in declared else None


def discover_pypi(repos, fetch_json=None, token=None):
    """Map ``full_name -> PyPI package`` for every repo that has one."""
    packages, notes = {}, []
    for repo in repos:
        try:
            package = pypi_package_for(repo, fetch_json=fetch_json, token=token)
        except (urllib.error.URLError, ValueError) as error:
            notes.append(f"{repo['full_name']}: PyPI lookup skipped ({error})")
            continue
        if package:
            packages[repo["full_name"]] = package
    return packages, notes


# --- source lookups ----------------------------------------------------------


def pypi_totals(packages, api_key=None, fetch_json=None, fetch_text=None):
    """All-time PyPI downloads per package. Exact with a key, rounded without."""
    # resolved here, not as a default argument, so the layer stays patchable
    fetch_json = fetch_json or globals()["fetch_json"]
    fetch_text = fetch_text or globals()["fetch_text"]
    totals, failures, notes = {}, {}, []
    for package in packages:
        errors = []
        count = None
        if api_key:
            try:
                payload = fetch_json(PEPY_V2.format(pkg=package), {"X-Api-Key": api_key})
                count = find_count(payload)
            except (urllib.error.URLError, ValueError) as error:
                errors.append(f"pepy v2 -> {error}")
            if count is None and not errors:
                errors.append("pepy v2 -> no total_downloads in response")
        else:
            notes.append("PEPY_API_KEY not set; using rounded shields.io figures for PyPI")
        if count is None:  # keyless fallback (or the keyed call failed)
            try:
                count = parse_shields_badge(fetch_text(SHIELDS_PYPI.format(pkg=package)))
            except (urllib.error.URLError, ValueError) as error:
                errors.append(f"shields.io -> {error}")
            if count is None and not any("shields.io" in e for e in errors):
                errors.append("shields.io -> no numeric value in badge")
        if count is not None:
            totals[package] = count
        else:
            failures[package] = "; ".join(errors) or "unknown error"
    return totals, failures, sorted(set(notes))


def jsdelivr_totals(repos, period=JSDELIVR_PERIOD, fetch_text=None):
    """jsDelivr hits per repo (``owner/repo``) for *period* (default: 12 months)."""
    fetch_text = fetch_text or globals()["fetch_text"]
    totals, failures = {}, {}
    for repo in repos:
        url = SHIELDS_JSDELIVR.format(period=period, repo=repo)
        try:
            count = parse_shields_badge(fetch_text(url))
        except (urllib.error.URLError, ValueError) as error:
            failures[repo] = f"{url} -> {error}"
            continue
        if count is None:
            failures[repo] = f"{url} -> no numeric value in badge"
            continue
        totals[repo] = count
    return totals, failures


def clone_counts(full_name, token, fetch_json=None):
    """Daily clone counts for the last 14 days: ``{"YYYY-MM-DD": count}``."""
    fetch_json = fetch_json or globals()["fetch_json"]
    payload = fetch_json(f"{GITHUB_API}/repos/{full_name}/traffic/clones", github_headers(token))
    return {entry["timestamp"][:10]: int(entry.get("count", 0)) for entry in payload.get("clones", [])}


def load_history(path):
    if not os.path.exists(path):
        return {"repos": {}}
    with open(path, encoding="utf-8") as handle:
        history = json.load(handle)
    history.setdefault("repos", {})
    return history


def save_history(path, history):
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(history, handle, indent=2, sort_keys=True)
        handle.write("\n")


# --- collection --------------------------------------------------------------


def collect(
    api_key=None,
    github_token=None,
    traffic_token=None,
    history=None,
    fetch_json=None,
    fetch_text=None,
):
    """Gather every figure. *history* is updated in place with clone data."""
    fetch_json = fetch_json or globals()["fetch_json"]
    fetch_text = fetch_text or globals()["fetch_text"]
    history = history if history is not None else {"repos": {}}

    repos = discover_repos(fetch_json=fetch_json, token=github_token)
    notes = []

    stars = sum(int(repo.get("stargazers_count") or 0) for repo in repos)
    forks = sum(int(repo.get("forks_count") or 0) for repo in repos)

    packages, pypi_notes = discover_pypi(repos, fetch_json=fetch_json, token=github_token)
    notes += pypi_notes
    pypi, pypi_failures, pypi_notes = pypi_totals(
        sorted(set(packages.values())), api_key=api_key, fetch_json=fetch_json, fetch_text=fetch_text
    )
    notes += pypi_notes

    jsdelivr, jsdelivr_failures = jsdelivr_totals(
        [repo["full_name"].lower() for repo in repos], fetch_text=fetch_text
    )

    clone_failures = {}
    if traffic_token:
        for repo in repos:
            full_name = repo["full_name"]
            try:
                daily = clone_counts(full_name, traffic_token, fetch_json=fetch_json)
            except (urllib.error.URLError, ValueError) as error:
                clone_failures[full_name] = f"traffic/clones -> {error}"
                continue
            merge_clones(history, full_name, daily)
    else:
        notes.append("TRAFFIC_TOKEN not set; clone counts were not refreshed")

    return {
        "repos": [repo["full_name"] for repo in repos],
        "stars": stars,
        "forks": forks,
        "packages": packages,
        "pypi": pypi,
        "jsdelivr": jsdelivr,
        "failures": {**pypi_failures, **jsdelivr_failures, **clone_failures},
        "notes": sorted(set(notes)),
        "download_sources": len(pypi) + len(jsdelivr),
        "downloads": sum(pypi.values()) + sum(jsdelivr.values()),
        "clones": history_total(history) if history.get("repos") else None,
    }


# --- entry point -------------------------------------------------------------


def main(argv=None):
    parser = argparse.ArgumentParser(description="Refresh the profile totals badges.")
    parser.add_argument("--readme", default="profile/README.md")
    parser.add_argument("--history", default=CLONE_HISTORY, help="clone history JSON")
    parser.add_argument("--dry-run", action="store_true", help="print the result, change nothing")
    parser.add_argument(
        "--allow-decrease",
        action="store_true",
        help="publish the download total even if it is lower than the published one",
    )
    args = parser.parse_args(argv)

    history = load_history(args.history)
    before = copy.deepcopy(history)
    try:
        result = collect(
            api_key=os.environ.get("PEPY_API_KEY") or None,
            github_token=os.environ.get("GITHUB_TOKEN") or None,
            traffic_token=os.environ.get("TRAFFIC_TOKEN") or None,
            history=history,
        )
    except (urllib.error.URLError, ValueError) as error:
        print(f"Could not list repositories ({error}); nothing was changed.", file=sys.stderr)
        return 1

    for note in result["notes"]:
        print(f"  note     {note}")
    print(f"  repos    {len(result['repos'])} public repos counted: {', '.join(sorted(result['repos']))}")
    for repo, package in sorted(result["packages"].items()):
        print(f"  package  {repo:<40} -> pypi/{package}")
    for name, count in sorted(result["pypi"].items()):
        print(f"  pypi     {name:<29} {count:>14,}")
    for name, count in sorted(result["jsdelivr"].items()):
        print(f"  jsdelivr {name:<29} {count:>14,}")
    for name, reason in sorted(result["failures"].items()):
        print(f"  FAILED   {name}: {reason}", file=sys.stderr)
    clones = result["clones"]
    print(f"  {'DOWNLOADS':<38} {result['downloads']:>14,}  ({format_count(result['downloads'])})")
    print(f"  {'CLONES':<38} {'n/a' if clones is None else f'{clones:,}'}")
    print(f"  {'STARS':<38} {result['stars']:>14,}")
    print(f"  {'FORKS':<38} {result['forks']:>14,}")

    # Never publish a download total we could not actually measure.
    if result["download_sources"] == 0:
        print("Every download source failed; the README and clone history are left untouched.", file=sys.stderr)
        return 1

    with open(args.readme, encoding="utf-8") as handle:
        original = handle.read()
    if not START_RE.search(original) and ANCHOR not in original:
        print(f"No badge block or anchor found in {args.readme}.", file=sys.stderr)
        return 1

    # Download totals only increase, so a drop means partial data. A published
    # 0 is a leftover from a failed run, not a real measurement.
    published = parse_badge_value(original)
    downloads_text = current_downloads_text(original) or NOT_AVAILABLE
    if published and result["downloads"] < published * (1 - DROP_TOLERANCE) and not args.allow_decrease:
        print(
            f"Refusing to publish {result['downloads']:,} downloads over {published:,} "
            f"(more than {DROP_TOLERANCE:.0%} below the published figure; looks like "
            "partial data -- pass --allow-decrease to override). Downloads badge kept.",
            file=sys.stderr,
        )
    else:
        downloads_text = format_count(result["downloads"])

    values = [
        ("Total Downloads", downloads_text),
        ("Total Clones", NOT_AVAILABLE if clones is None else format_count(clones)),
        ("Total Stars", format_count(result["stars"])),
        ("Total Forks", format_count(result["forks"])),
    ]

    if args.dry_run:
        print("--dry-run: nothing written")
        return 0

    if history != before:
        save_history(args.history, history)
        print(f"Updated clone history in {args.history}.")

    updated, changed = update_readme(original, values)
    if not changed:
        print(f"Badges already up to date in {args.readme}.")
        return 0
    with open(args.readme, "w", encoding="utf-8") as handle:
        handle.write(updated)
    print(f"Updated the badges in {args.readme}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
